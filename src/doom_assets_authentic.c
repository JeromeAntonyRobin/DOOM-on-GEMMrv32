// Gap-Free Scaled Rasterizer for Billboarded Monsters (Depth-tested and vertical aperture-clipped)
void draw_authentic_patch_scaled(volatile uint8_t *vram, const doom_patch_t *patch, int screenX, int screenY, int spr_w, int spr_h, fixed_t tz) {
    const uint8_t *data = patch->data;
    int w = patch->width;
    int h = patch->height;
    if (w <= 0 || h <= 0 || spr_w <= 0 || spr_h <= 0) return;

    const uint32_t *col_offsets = (const uint32_t *)(data + 8);
    int drawStartX = screenX - spr_w / 2;
    int drawEndX   = drawStartX + spr_w - 1;
    if (drawStartX < 0) drawStartX = 0;
    if (drawEndX >= SCREEN_W) drawEndX = SCREEN_W - 1;

    for (int sx = drawStartX; sx <= drawEndX; sx++) {
        // 1. Horizontal depth test against closest solid wall (only for 3D world mobjs)
        if (tz > 0 && tz >= wall_dist_buffer[sx]) continue;

        // 2. Vertical clipping boundaries: stop at screen top and weapon silhouette
        int clip_top = 0;
        int clip_bot = (tz > 0) ? ((int)weapon_top_clip[sx] - 1) : (VIEWPORT_H - 1);

        // 3. Occlude against foreground portal / step riser (e.g. stairs, ledges)
        if (tz > 0 && tz > portal_dist_buffer[sx]) {
            if (portal_ceilingclip[sx] >= portal_floorclip[sx]) continue;
            if (portal_ceilingclip[sx] + 1 > clip_top) clip_top = portal_ceilingclip[sx] + 1;
            if (portal_floorclip[sx] - 1 < clip_bot)   clip_bot = portal_floorclip[sx] - 1;
        }

        if (clip_top > clip_bot) continue;

        int patch_col = ((sx - (screenX - spr_w / 2)) * w) / spr_w;
        if (patch_col < 0) patch_col = 0;
        if (patch_col >= w) patch_col = w - 1;
        uint32_t ofs = col_offsets[patch_col];

        while (1) {
            uint8_t topdelta = data[ofs];
            if (topdelta == 0xFF) break;
            uint8_t length = data[ofs + 1];
            const uint8_t *src = data + ofs + 3;

            // Compute exact screen bounds for this post
            int raw_dest_y0 = screenY + (topdelta * spr_h) / h;
            int raw_dest_y1 = screenY + ((topdelta + length) * spr_h) / h;
            int raw_post_h = raw_dest_y1 - raw_dest_y0;
            if (raw_post_h <= 0) {
                ofs += 4 + length;
                continue;
            }

            // Clip vertically to visible room aperture (prevents bleeding through step risers and ledges)
            int dest_y0 = (raw_dest_y0 < clip_top) ? clip_top : raw_dest_y0;
            int dest_y1 = (raw_dest_y1 > clip_bot + 1) ? (clip_bot + 1) : raw_dest_y1;
            if (dest_y0 < 0) dest_y0 = 0;
            if (dest_y1 > VIEWPORT_H) dest_y1 = VIEWPORT_H;

            if (dest_y0 < dest_y1) {
                fixed_t step = ((fixed_t)length << 16) / raw_post_h;
                fixed_t tex_pos = (dest_y0 - raw_dest_y0) * step;
                volatile uint8_t *dest = &vram[dest_y0 * SCREEN_W + sx];
                for (int dy = dest_y0; dy < dest_y1; dy++, dest += SCREEN_W) {
                    int src_i = (tex_pos >> 16);
                    tex_pos += step;
                    if (src_i >= 0 && src_i < length) {
                        *dest = src[src_i];
                    }
                }
            }
            ofs += 4 + length;
        }
    }
}
